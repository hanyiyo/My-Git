CREATE TABLE reception_queue (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    appointment_id VARCHAR(36) NOT NULL UNIQUE,
    schedule_id VARCHAR(36) NOT NULL,
    doctor_id VARCHAR(36) NOT NULL,
    patient_id VARCHAR(36) NOT NULL,
    queue_group TINYINT NOT NULL,
    queued_at BIGINT NOT NULL,
    checked_in_at BIGINT NOT NULL,
    restoration_count TINYINT NOT NULL DEFAULT 0,
    state VARCHAR(24) NOT NULL,
    called_at BIGINT NULL,
    started_at BIGINT NULL,
    missed_at BIGINT NULL,
    completed_at BIGINT NULL,
    FOREIGN KEY (appointment_id) REFERENCES appointment(id),
    FOREIGN KEY (schedule_id) REFERENCES schedule(id),
    FOREIGN KEY (doctor_id) REFERENCES account(id),
    FOREIGN KEY (patient_id) REFERENCES account(id),
    CHECK (queue_group BETWEEN 1 AND 3),
    CHECK (restoration_count BETWEEN 0 AND 1),
    CHECK (state IN ('WAITING', 'CALLED', 'IN_CONSULTATION', 'MISSED', 'COMPLETED')),
    INDEX reception_order (schedule_id, state, queue_group, queued_at, id),
    INDEX reception_doctor (doctor_id, schedule_id, state)
);
