test('科室目录 A/B/C 变体支持出诊方式、挂号预约和 URL 切换', async ({ page }) => {
  const apiRequests: string[] = []
  page.on('request', request => { if (request.url().includes('/api/')) apiRequests.push(request.url()) })
  const headings = {
    A: '科室信息',
    B: '找到今天适合你的门诊',
    C: '全科医学科',
  } as const
  for (const variant of ['A', 'B', 'C'] as const) {
    await page.goto(`/prototype/patient-home/departments?variant=${variant}`)
    await expect(page.getByTestId('department-page')).toBeVisible()
    await expect(page.getByRole('heading', { name: headings[variant] })).toBeVisible()
    await expect(page).toHaveURL(new RegExp(`departments\\?variant=${variant}$`))
    await expect(page.locator('.ph-directory-breadcrumb')).toHaveCount(0)
    if (variant === 'A') await expect(page.getByText('不知道挂什么科？', { exact: true })).toHaveCount(0)

    if (variant === 'A' || variant === 'B') {
      const list = await page.locator(variant === 'A' ? '.ph-dept-a-sidebar' : '.ph-dept-b-list').boundingBox()
      const detail = await page.locator(variant === 'A' ? '.ph-dept-a-main' : '.ph-dept-b-main').boundingBox()
      expect(list).toBeTruthy()
      expect(detail).toBeTruthy()
      expect(Math.abs(detail!.y - list!.y)).toBeLessThan(2)
      expect(detail!.x - (list!.x + list!.width)).toBeGreaterThanOrEqual(0)
      expect(detail!.x - (list!.x + list!.width)).toBeLessThanOrEqual(24)
      expect(detail!.width).toBeGreaterThan(500)
    }

    const modeTabs = page.getByRole('tab')
    await expect(modeTabs).toHaveCount(2)
    await modeTabs.nth(1).click()
    await expect(page.getByRole('button', { name: '立即挂号', exact: true }).first()).toBeVisible()
    await page.getByRole('button', { name: '立即挂号', exact: true }).last().click()
    await expect(page).toHaveURL(new RegExp(`departments\\?variant=${variant}&view=registration$`))
    const registration = page.getByTestId('registration-page')
    await expect(registration.getByRole('heading', { name: '立即挂号' })).toBeVisible()
    await expect(registration.getByRole('button', { name: /确认挂号/ })).toBeVisible()
    await page.getByRole('navigation', { name: '顶部快捷导航' }).getByRole('button', { name: '科室信息', exact: true }).click()
    await expect(page).toHaveURL(new RegExp(`departments\\?variant=${variant}$`))

    await page.getByRole('button', { name: '预约', exact: true }).first().click()
    await expect(page).toHaveURL(new RegExp(`departments\\?variant=${variant}&view=registration$`))
    await expect(page.getByTestId('registration-page').getByRole('heading', { name: '立即挂号' })).toBeVisible()
  }
  expect(apiRequests).toEqual([])
})

