import { test, expect } from '@playwright/test'

test('首页三个结构方案通过URL与键盘切换，侧栏可以收缩', async ({ page }) => {
  const apiRequests: string[] = []
  page.on('request', request => { if (request.url().includes('/api/')) apiRequests.push(request.url()) })
  await page.goto('/prototype/patient-home?variant=A')
  await expect(page.getByRole('heading', { name: '上午好，林同学。' })).toBeVisible()
  await expect(page.getByRole('heading', { name: '让每一次就医，都更从容一点。' })).toBeVisible()
  await expect(page.getByRole('link', { name: '智能医疗问诊预约系统首页' })).toBeVisible()
  const topNav = page.getByRole('navigation', { name: '顶部快捷导航' })
  for (const label of ['医生团队', '科室信息', '立即挂号', '我的挂号', '站内通知']) await expect(topNav.getByRole('button', { name: label, exact: true })).toBeVisible()
  const sidebar = page.getByRole('complementary', { name: '患者端侧栏' })
  await expect(sidebar.getByRole('navigation')).toBeVisible()
  await sidebar.getByRole('button', { name: '打开个人中心' }).click()
  await expect(page.getByRole('dialog').getByText('患者账户 · 虚构演示资料')).toBeVisible()
  await page.keyboard.press('Escape')
  await sidebar.getByRole('button', { name: '收起侧栏', exact: true }).click()
  await expect(sidebar.getByRole('button', { name: '展开侧栏', exact: true })).toHaveAttribute('aria-expanded', 'false')
  await expect(sidebar.getByRole('button', { name: '科室信息', exact: true })).toBeVisible()
  await sidebar.getByRole('button', { name: '展开侧栏', exact: true }).click()
  await page.getByRole('button', { name: '下一个方案' }).click()
  await expect(page).toHaveURL(/variant=B/)
  await expect(page.getByTestId('variant-B')).toBeVisible()
  await expect(page.getByRole('heading', { name: '今天的就诊旅程' })).toBeVisible()
  await page.keyboard.press('ArrowRight')
  await expect(page).toHaveURL(/variant=C/)
  await expect(page.getByTestId('variant-C')).toBeVisible()
  await page.reload()
  await expect(page.getByTestId('variant-C')).toBeVisible()
  await page.keyboard.press('ArrowRight')
  await expect(page).toHaveURL(/variant=A/)
  await expect(page.getByLabel('原型当前状态')).toContainText('虚构数据')
  await expect(page.getByRole('heading', { name: '就诊流程，一看就懂' })).toBeVisible()
  await expect(page.getByRole('main')).toContainText('就诊科室：全科医学科')
  await page.getByRole('button', { name: '查看第2条公告' }).click()
  await expect(page.getByRole('heading', { name: /先预约，再签到/ })).toBeVisible()
  await page.getByRole('button', { name: '查看第3条公告' }).click()
  await expect(page.getByRole('heading', { name: /关注门诊动态/ })).toBeVisible()
  expect(apiRequests).toEqual([])
})

test('快捷入口携带就诊模式与挂号筛选，签到和两类缴费相互独立', async ({ page }) => {
  await page.goto('/prototype/patient-home?variant=A')
  await page.getByRole('navigation', { name: '顶部快捷导航' }).getByRole('button', { name: '我的挂号', exact: true }).click()
  const appointmentDialog = page.getByRole('dialog')
  await expect(appointmentDialog.getByRole('tab', { name: '全部', exact: true })).toHaveAttribute('aria-selected', 'true')
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: '查看我的预约' }).click()
  await expect(appointmentDialog.getByRole('heading', { name: '我的挂号' })).toBeVisible()
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: /线上问诊预约 预约医生/ }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog.getByLabel('就诊类型')).toHaveValue('线上问诊')
  await dialog.getByRole('button', { name: /选择此号源/ }).click()
  await expect(dialog.getByRole('tab', { name: '待付款', exact: true })).toHaveAttribute('aria-selected', 'true')
  await dialog.getByRole('button', { name: '模拟支付挂号费 ¥12.00' }).click()
  await expect(dialog.getByRole('tab', { name: '待就诊', exact: true })).toHaveAttribute('aria-selected', 'true')
  await dialog.getByRole('button', { name: '模拟签到', exact: true }).click()
  await expect(dialog.getByRole('status').filter({ hasText: '签到成功' })).toBeVisible()
  await expect(dialog.getByRole('button', { name: '已签到，等待叫号' })).toBeDisabled()
  await dialog.getByRole('tab', { name: '待付款', exact: true }).click()
  await expect(dialog.getByRole('button', { name: '模拟支付药费 ¥18.00' })).toBeEnabled()
  await dialog.getByRole('button', { name: '模拟支付药费 ¥18.00' }).click()
  await expect(dialog.getByRole('button', { name: '已支付', exact: true })).toBeDisabled()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('main')).toContainText('候诊中')
  await page.getByRole('button', { name: /线下门诊挂号 选择时段/ }).click()
  await expect(dialog.getByLabel('就诊类型')).toHaveValue('线下面诊')
  await page.keyboard.press('Escape')
  for (const [buttonName, tab] of [['快速签到 签到入队', '待就诊'], ['缴费中心 挂号费', '待付款'], ['查看报告 查看已完成', '已完成']]) {
    await page.getByRole('button', { name: new RegExp(buttonName!) }).click()
    await expect(dialog.getByRole('tab', { name: tab!, exact: true })).toHaveAttribute('aria-selected', 'true')
    await page.keyboard.press('Escape')
  }
  await page.getByRole('button', { name: /科室信息 了解科室/ }).click()
  await expect(page).toHaveURL(/\/prototype\/patient-home\/departments/)
  await page.getByRole('button', { name: /口腔科 口腔检查/ }).click()
  await expect(page.getByRole('heading', { name: '口腔科' })).toBeVisible()
  await page.getByTestId('department-page').getByRole('button', { name: '立即挂号', exact: true }).click()
  await expect(dialog.getByLabel('选择科室')).toHaveValue('口腔科')
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: '返回患者首页' }).click()
  await page.getByRole('button', { name: /医生团队 查看医生/ }).click()
  await expect(dialog.getByText('许知遥')).toBeVisible()
})

