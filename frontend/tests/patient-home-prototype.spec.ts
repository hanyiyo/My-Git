test('AI抽屉要求本次授权，选图后重新授权，方向键不打断输入且不外发材料', async ({ page }) => {
  const apiRequests: string[] = []
  page.on('request', request => { if (request.url().includes('/api/')) apiRequests.push(request.url()) })
  await page.goto('/prototype/patient-home?variant=C')
  await page.getByRole('button', { name: '打开AI导诊助手' }).click()
  const dialog = page.getByRole('dialog')
  const ask = dialog.getByRole('button', { name: '获取演示科室建议' })
  await expect(ask).toBeDisabled()
  await dialog.getByLabel('你想了解什么？').fill('最近嗓子不舒服')
  await page.keyboard.press('ArrowLeft')
  await expect(page).toHaveURL(/variant=C/)
  await expect(ask).toBeDisabled()
  await dialog.getByRole('checkbox').check()
  await dialog.getByLabel('添加检查图片', { exact: true }).setInputFiles({ name: 'fictional-report.png', mimeType: 'image/png', buffer: Buffer.from('prototype fixture') })
  await expect(ask).toBeDisabled()
  await dialog.getByRole('checkbox').check()
  await ask.click()
  await expect(dialog.getByRole('status')).toContainText('演示导诊建议')
  await expect(dialog.getByRole('status')).toContainText('不进行图片识别')
  await dialog.getByLabel('你想了解什么？').fill('想了解检查流程')
  await expect(ask).toBeDisabled()
  await expect(dialog.getByRole('status')).toHaveCount(0)
  await dialog.getByRole('checkbox').check()
  await ask.click()
  await dialog.getByRole('button', { name: '查看全科号源' }).click()
  await expect(page).toHaveURL(/\/prototype\/patient-home\/departments\?variant=C&view=registration/)
  await expect(page.getByTestId('registration-page').getByRole('heading', { name: '立即挂号' })).toBeVisible()
  expect(apiRequests).toEqual([])
})

