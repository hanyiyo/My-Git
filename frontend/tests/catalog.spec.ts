import { test, expect, type Page } from '@playwright/test'

const password = 'fictional-browser-password'
async function registerDoctor(page: Page, name: string) {
  await page.goto('/login')
  await page.getByRole('button', { name: '患者或医生注册' }).click()
  await page.getByLabel('账号', { exact: true }).fill(name)
  await page.getByLabel('密码', { exact: true }).fill(password)
  await page.getByLabel('注册身份').selectOption('DOCTOR')
  await page.getByRole('button', { name: '注册', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('注册成功')
}
async function login(page: Page, name: string, pass = password) {
  await page.getByLabel('账号', { exact: true }).fill(name)
  await page.getByLabel('密码', { exact: true }).fill(pass)
  await expect(page.getByAltText('图形验证码')).toBeVisible()
  await page.getByLabel('图形验证码', { exact: true }).fill('AB7K')
  await page.getByRole('button', { name: '登录', exact: true }).click()
}
async function logout(page: Page) {
  await page.getByRole('link', { name: '返回工作台' }).click()
  await page.getByRole('button', { name: '退出登录' }).click()
  await expect(page).toHaveURL(/\/login$/)
}

test('管理员维护目录并发布排班，患者查询有效资源，医生查看自己的认证与排班', async ({ page, browser }) => {
  test.setTimeout(180000)
  const account = `doctor-${crypto.randomUUID()}`
  const department = `演示科室-${crypto.randomUUID().slice(0, 8)}`
  const doctorName = `虚构林医生-${crypto.randomUUID().slice(0, 8)}`
  await registerDoctor(page, account)
  await login(page, account)
  await expect(page).toHaveURL(/\/doctor$/)
  await expect(page.getByRole('link', { name: '我的认证与排班' })).toBeVisible()
  await page.getByRole('link', { name: '我的认证与排班' }).click()
  await expect(page.getByText('认证状态：待审核', { exact: true })).toBeVisible()
  await logout(page)
  await login(page, 'admin-foundation-test', 'fictional-test-administrator-password')
  await expect(page).toHaveURL(/\/admin$/)
  await page.getByRole('link', { name: '医院目录与排班管理' }).click()
  await page.getByLabel('医院名称', { exact: true }).fill('虚构浏览器校医院')
  await page.getByLabel('医院地址').fill('虚构浏览器路一号')
  await page.getByLabel('医院服务说明').fill('仅使用虚构演示资料')
  await page.getByRole('button', { name: '保存医院信息' }).click()
  await expect(page.getByRole('status')).toContainText('医院信息已保存')
  await page.getByLabel('科室名称', { exact: true }).fill(department)
  await page.getByLabel('科室说明').fill('演示诊疗服务')
  await page.getByRole('button', { name: '保存科室' }).click()
  await expect(page.getByRole('status')).toContainText('科室已保存')
  await page.getByLabel('医生账户').selectOption({ label: account })
  await page.getByLabel('医生姓名').fill(doctorName)
  await page.getByLabel('医生职称').fill('主治医师')
  await page.getByLabel('医生简介').fill('虚构医生基本资料')
  await page.getByLabel('医生所属科室').selectOption({ label: department })
  await page.getByLabel('认证状态', { exact: true }).selectOption('CERTIFIED')
  await page.getByRole('button', { name: '保存医生资料' }).click()
  await expect(page.getByRole('status')).toContainText('医生资料已保存')
  await page.getByLabel('排班医生').selectOption({ label: doctorName })
  await page.getByLabel('排班科室').selectOption({ label: department })
  await page.getByLabel('出诊日期').fill(new Date(Date.now() + 3 * 86400000).toISOString().slice(0, 10))
  await page.getByLabel('门诊时段').selectOption('AM')
  await page.getByLabel('服务方式', { exact: true }).selectOption('ONLINE')
  await page.getByLabel('号源数量').fill('3')
  await page.getByLabel('挂号费用（分）').fill('1200')
  await page.getByRole('button', { name: '发布排班' }).click()
  await expect(page.getByRole('status')).toContainText('排班已发布')
  await page.getByRole('button', { name: '发布排班' }).click()
  await expect(page.getByRole('alert')).toContainText('已有排班')
  await logout(page)
  await page.getByRole('button', { name: '患者或医生注册' }).click()
  const patient = `patient-${crypto.randomUUID()}`
  await page.getByLabel('账号', { exact: true }).fill(patient)
  await page.getByLabel('密码', { exact: true }).fill(password)
  await page.getByRole('button', { name: '注册', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('注册成功')
  await login(page, patient)
  await expect(page).toHaveURL(/\/patient$/)
  await page.getByRole('link', { name: '查询科室、医生与排班' }).click()
  await expect(page.getByText('虚构浏览器路一号')).toBeVisible()
  await page.getByLabel('查询科室').selectOption({ label: department })
  await page.getByRole('button', { name: '查询排班' }).click()
  const resource = page.getByRole('listitem').filter({ hasText: doctorName })
  await expect(resource).toHaveCount(1)
  await expect(resource).toContainText('线上')
  await expect(resource).toContainText('上午')
  await expect(resource).toContainText('可用号源：3')
  await expect(resource).toContainText('12.00')
  await page.setViewportSize({ width: 375, height: 812 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  const adminContext = await browser.newContext()
  try {
    const adminPage = await adminContext.newPage()
    await adminPage.goto('/login')
    await login(adminPage, 'admin-foundation-test', 'fictional-test-administrator-password')
    await expect(adminPage).toHaveURL(/\/admin$/)
    await adminPage.getByRole('link', { name: '医院目录与排班管理' }).click()
    await adminPage.getByLabel('编辑已有科室').selectOption({ label: department })
    await adminPage.getByLabel('科室状态').selectOption('false')
    await adminPage.getByRole('button', { name: '保存科室' }).click()
    await expect(adminPage.getByRole('status')).toContainText('科室已保存')
    await logout(adminPage)
  } finally { await adminContext.close() }
  await page.getByRole('button', { name: '查询排班' }).click()
  await expect(page.getByRole('listitem').filter({ hasText: doctorName })).toHaveCount(0)
  await expect(page.getByLabel('查询科室').getByRole('option', { name: department, exact: true })).toHaveCount(0)
  await logout(page)
  await login(page, account)
  await expect(page).toHaveURL(/\/doctor$/)
  await page.getByRole('link', { name: '我的认证与排班' }).click()
  await expect(page.getByText('认证状态：已认证', { exact: true })).toBeVisible()
  await expect(page.getByRole('listitem').filter({ hasText: '线上' })).toContainText('可用号源：3')
})
