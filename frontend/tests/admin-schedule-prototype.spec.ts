import { test, expect } from '@playwright/test'

test('管理员排班工作台展示月历、日期详情和独立排班入口', async ({ page }) => {
  const apiRequests: string[] = []
  page.on('request', request => { if (request.url().includes('/api/')) apiRequests.push(request.url()) })
  await page.goto('/prototype/admin-schedules')
  await expect(page.getByRole('heading', { name: '排班管理工作台' })).toBeVisible()
  await expect(page.getByRole('button', { name: '＋新增排班' })).toHaveCSS('background-color', 'rgb(237, 245, 254)')
  await expect(page.locator('[aria-label="排班月历"]')).toBeVisible()
  await expect(page.getByRole('complementary', { name: '所选日期详情' })).toContainText('11月13日')
  await expect(page.getByRole('region', { name: '上午排班' })).toContainText('上午')
  await expect(page.getByRole('region', { name: '下午排班' })).toContainText('下午')
  await expect(page.getByRole('button', { name: '新增排班 2026-11-13' })).toBeVisible()
  await expect(page.getByRole('button', { name: '删除排班 2026-11-13' })).toBeDisabled()
  await page.locator('[data-calendar-date="2026-11-14"]').click()
  await expect(page.getByRole('complementary', { name: '所选日期详情' })).toContainText('11月14日')
  expect(apiRequests).toEqual([])
})

test('月历日期卡片下方可新增排班，表单日期使用日历下拉框并校验冲突', async ({ page }) => {
  await page.goto('/prototype/admin-schedules')
  await page.getByRole('button', { name: '新增排班 2026-11-20' }).click()
  const dialog = page.getByRole('dialog', { name: '新增排班' })
  await expect(dialog.getByRole('button', { name: '出诊日期' })).toBeVisible()
  await dialog.getByLabel('医生').selectOption('马凌')
  await dialog.getByLabel('门诊时段').selectOption('pm')
  await dialog.getByLabel('服务方式').selectOption('online')
  await dialog.getByLabel('总号源').fill('18')
  await dialog.getByRole('button', { name: '保存草稿' }).click()
  await expect(page.getByRole('complementary', { name: '所选日期详情' })).toContainText('11月20日')
  await expect(page.getByRole('complementary', { name: '所选日期详情' })).toContainText('马凌')

  await page.getByRole('button', { name: '新增排班 2026-11-13' }).click()
  const conflict = page.getByRole('dialog', { name: '新增排班' })
  await conflict.getByLabel('医生').selectOption('周宁')
  await conflict.getByLabel('门诊时段').selectOption('am')
  await conflict.getByRole('button', { name: '保存草稿' }).click()
  await expect(page.getByRole('status')).toContainText('同一医生同一时段已有排班')
})

test('新增排班可直接发布，保存草稿和发布按钮使用清晰的对比色', async ({ page }) => {
  await page.goto('/prototype/admin-schedules')
  await page.getByRole('button', { name: '新增排班 2026-11-21' }).click()
  const dialog = page.getByRole('dialog', { name: '新增排班' })
  const draft = dialog.getByRole('button', { name: '保存草稿' })
  const publish = dialog.getByRole('button', { name: '发布排班' })
  await expect(draft).toBeVisible()
  await expect(publish).toBeVisible()
  await expect(draft).toHaveCSS('color', 'rgb(94, 136, 171)')
  await expect(publish).toHaveCSS('background-color', 'rgb(52, 124, 219)')
  await dialog.getByLabel('医生').selectOption('马凌')
  await dialog.getByLabel('门诊时段').selectOption('pm')
  await publish.click()
  await expect(page.getByRole('region', { name: '下午排班' })).toContainText('已发布')
  await expect(page.getByRole('region', { name: '下午排班' })).toContainText('马凌')
})

test('从排班详情编辑草稿时先收回右侧抽屉并打开可编辑表单', async ({ page }) => {
  await page.goto('/prototype/admin-schedules')
  await page.locator('[data-calendar-date="2026-11-14"]').click()
  await page.locator('.schedule-card').first().click()
  const drawer = page.getByRole('complementary', { name: '排班详情' })
  await drawer.getByRole('button', { name: '编辑草稿' }).click()
  await expect(drawer).toBeHidden()
  const dialog = page.getByRole('dialog', { name: '编辑排班' })
  await expect(dialog.getByLabel('医生')).toBeEnabled()
  await dialog.getByLabel('总号源').fill('21')
  await expect(dialog.getByLabel('总号源')).toHaveValue('21')
})

test('排班草稿支持发布，日期减号可删除无预约排班', async ({ page }) => {
  await page.goto('/prototype/admin-schedules')
  await page.locator('[data-calendar-date="2026-11-14"]').click()
  await page.locator('.schedule-card').first().click()
  const detail = page.getByRole('complementary', { name: '排班详情' })
  await expect(detail).toContainText('周宁')
  await expect(detail).toContainText('线上问诊')
  await expect(detail).toContainText('业务影响')
  await detail.getByRole('button', { name: '关闭排班详情' }).click()
  await expect(detail).toBeHidden()
  await page.locator('.schedule-card').first().click()
  await page.getByRole('complementary', { name: '排班详情' }).getByRole('button', { name: '发布排班' }).click()
  await expect(page.getByRole('complementary', { name: '排班详情' }).getByRole('status')).toContainText('排班已发布')
  await page.getByRole('complementary', { name: '排班详情' }).getByRole('button', { name: '关闭排班详情' }).click()
  await page.getByRole('button', { name: '删除排班 2026-11-14' }).click()
  const confirm = page.getByRole('dialog', { name: '确认删除排班' })
  await expect(confirm).toContainText('没有已挂号患者')
  await confirm.getByRole('button', { name: '确认删除' }).click()
  await expect(page.getByRole('region', { name: '上午排班' })).toContainText('上午暂无排班')
  await expect(page.getByRole('region', { name: '下午排班' })).toContainText('下午暂无排班')
  await page.locator('[data-calendar-date="2026-11-13"]').click()
  await expect(page.getByRole('button', { name: '删除排班 2026-11-13' })).toBeDisabled()
})

