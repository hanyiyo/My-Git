import { test, expect } from '@playwright/test'

test('患者资源工作台展示资料目录、日历筛选和新增闭环', async ({ page }) => {
  await page.goto('/prototype/admin-patients')
  await expect(page.getByRole('heading', { name: '患者资源工作台' })).toBeVisible()
  await expect(page.getByRole('heading', { name: /患者资料目录/ })).toBeVisible()
  await page.getByRole('button', { name: '注册日期' }).click()
  await page.getByRole('dialog', { name: '注册日期日历' }).getByRole('button', { name: '2026-05-21' }).click()
  await expect(page).toHaveURL(/date=2026-05-21/)
  await expect(page.getByText('沈嘉禾')).toBeVisible()
  await page.getByRole('button', { name: '新增患者' }).click()
  const form = page.getByRole('dialog', { name: '新增患者' })
  await form.getByLabel('姓名').fill('测试患者')
  await form.getByLabel('手机号').fill('13800001111')
  await form.getByLabel('登录账号').fill('test.patient')
  await form.getByRole('button', { name: '创建患者账户' }).click()
  await expect(page.getByRole('complementary', { name: '资源详情' })).toContainText('测试患者')
})

test('患者资源工作台启停账户需要二次确认', async ({ page }) => {
  await page.goto('/prototype/admin-patients')
  await page.getByRole('button', { name: '查看P-1007详情' }).click()
  const drawer = page.getByRole('complementary', { name: '资源详情' })
  await drawer.getByRole('button', { name: '停用账户' }).click()
  const confirm = page.getByRole('dialog', { name: '确认停用账户' })
  await expect(confirm).toContainText('不会删除患者资料')
  await confirm.getByRole('button', { name: '确认停用账户' }).click()
  await expect(drawer).toContainText('停用账户已完成')
})

test('医生治理工作台支持资质审核备注和科室归属', async ({ page }) => {
  await page.goto('/prototype/admin-doctors')
  await expect(page.getByRole('heading', { name: '医生治理工作台' })).toBeVisible()
  await page.getByRole('button', { name: '查看D-1098详情' }).click()
  const drawer = page.getByRole('complementary', { name: '资源详情' })
  await drawer.getByRole('button', { name: '审核资质' }).click()
  const review = page.getByRole('dialog', { name: '审核医生资质' })
  await review.getByLabel('审核结果').selectOption('CERTIFIED')
  await review.getByLabel('审核备注').fill('执业材料已核验。')
  await review.getByRole('button', { name: '保存审核结果' }).click()
  await expect(drawer.getByRole('status')).toContainText('资质状态和审核备注已保存')
  await expect(drawer).toContainText('已认证')
  await drawer.getByRole('button', { name: '调整科室' }).click()
  await expect(page.getByRole('dialog', { name: '调整医生科室' })).toBeVisible()
})

test('科室管理工作台支持负责人任命和停用影响提示', async ({ page }) => {
  await page.goto('/prototype/admin-departments')
  await expect(page.getByRole('heading', { name: '科室管理工作台' })).toBeVisible()
  await page.getByRole('button', { name: '查看DEP-01详情' }).click()
  const drawer = page.getByRole('complementary', { name: '资源详情' })
  await drawer.getByRole('button', { name: '任命 / 更换科主任' }).click()
  const head = page.getByRole('dialog', { name: '任命科主任' })
  await head.getByLabel('本科室已认证医生').selectOption('D-1021')
  await head.getByRole('button', { name: '保存负责人' }).click()
  await expect(drawer.getByRole('status')).toContainText('已任命周宁为科主任')
  await drawer.getByRole('button', { name: '停用科室' }).click()
  const confirm = page.getByRole('dialog', { name: '确认停用科室' })
  await expect(confirm).toContainText('禁止新排班和新预约')
  await confirm.getByRole('button', { name: '确认停用科室' }).click()
  await expect(drawer).toContainText('停用科室已完成')
})

test('资源工作台移动宽度无横向溢出且导航可切换', async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 812 })
  await page.goto('/prototype/admin-departments')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.getByRole('button', { name: '打开侧栏' }).click()
  await expect(page.getByRole('complementary', { name: '管理员端导航' })).toBeVisible()
  await page.getByRole('button', { name: '患者', exact: true }).click()
  await expect(page).toHaveURL(/\/prototype\/admin-patients/)
})
