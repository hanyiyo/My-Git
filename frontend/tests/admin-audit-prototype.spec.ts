test('桌面与手机布局无页面溢出，所有工作台按钮样式可见且可操作', async ({ page }) => {
  for (const viewport of [{ width: 1440, height: 1000 }, { width: 375, height: 812 }]) {
    await page.setViewportSize(viewport)
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    const search = page.getByLabel('审计日志关键词')
    await expect(search).toBeVisible()
    await expect(page.getByRole('button', { name: '重置筛选', exact: true })).toHaveCSS('background-color', 'rgb(255, 255, 255)')
    const action = table(page).locator('tbody tr').first().getByRole('button')
    await action.click()
    await expect(drawer(page)).toBeVisible()
    for (const button of await drawer(page).getByRole('button').all()) {
      await expect(button).toHaveCSS('display', /^(inline-)?flex$/)
      await expect(button).toHaveCSS('width', /px$/)
      const box = await button.boundingBox()
      expect(box!.width).toBeGreaterThan(24)
      expect(box!.height).toBeGreaterThanOrEqual(32)
      expect(box!.x + box!.width).toBeLessThanOrEqual(viewport.width)
    }
    await expect(drawer(page).getByRole('button', { name: '复制日志编号' })).toHaveCSS('background-color', 'rgb(52, 124, 219)')
    await drawer(page).getByRole('button', { name: '关闭日志详情' }).click()
  }
})

test('使用医院业务日而非浏览器当地日期，午夜不生成未来日志', async ({ browser }) => {
  const context = await browser.newContext({ timezoneId: 'America/Los_Angeles' })
  try {
    const page = await context.newPage()
    await page.clock.install({ time: new Date('2026-11-14T16:00:20Z') })
    await page.goto(url)
    await expect(page.getByLabel('结束日期')).toHaveValue('2026-11-15')
    await expect(page.getByLabel('开始日期')).toHaveValue('2026-11-09')
    await expect(table(page).locator('tbody tr').first()).toContainText('2026-11-15 00:00:19')
    const first = await table(page).locator('time').first().getAttribute('datetime')
    expect(Date.parse(first!)).toBeLessThan(Date.parse('2026-11-14T16:00:20Z'))
  } finally { await context.close() }
})
