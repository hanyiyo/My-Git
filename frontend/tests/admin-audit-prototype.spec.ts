import { test, expect, type Page } from '@playwright/test'

const url = '/prototype/admin-home?module=审计日志'
const table = (page: Page) => page.getByRole('table', { name: '审计日志', exact: true })
const drawer = (page: Page) => page.getByRole('dialog', { name: '审计日志详情' })
const stat = (page: Page, label: string) => page.getByLabel('审计日志摘要').locator('article').filter({ hasText: label }).locator('strong')

test.beforeEach(async ({ page }) => {
  await page.clock.install({ time: new Date('2026-11-14T02:00:00Z') })
  await page.goto(url)
})

test('原管理员菜单进入只读审计工作台，摘要统计全部筛选结果', async ({ page }) => {
  const requests: string[] = []
  page.on('request', request => { if (request.url().includes('/api/')) requests.push(request.url()) })
  await page.goto('/prototype/admin-home')
  await page.getByRole('navigation', { name: '管理员功能导航' }).getByRole('button', { name: '审计日志', exact: true }).click()
  await expect(page.getByRole('heading', { name: '审计日志工作台' })).toBeVisible()
  await expect(page.getByText('虚构演示数据', { exact: true })).toBeVisible()
  await expect(page.getByLabel('开始日期')).toHaveValue('2026-11-08')
  await expect(page.getByLabel('结束日期')).toHaveValue('2026-11-14')
  await expect(page.getByLabel('业务模块')).toHaveValue('全部模块')
  await expect(stat(page, '日志总数')).toHaveText('28')
  await expect(stat(page, '涉及管理员')).toHaveText('3')
  await expect(stat(page, '涉及模块')).toHaveText('9')
  await expect(table(page).locator('tbody tr')).toHaveCount(10)
  await expect(page.getByLabel('日志分页')).toContainText('1 / 3')
  await expect(page.getByRole('button', { name: '上一页', exact: true })).toBeDisabled()
  expect(requests).toEqual([])
})

test('模块和关键词组合筛选、统计联动及空结果重置', async ({ page }) => {
  await page.getByLabel('业务模块').selectOption('药品库存')
  await expect(stat(page, '日志总数')).toHaveText('5')
  await expect(stat(page, '涉及模块')).toHaveText('1')
  await page.getByLabel('审计日志关键词').fill('  med-001  ')
  await expect(table(page).locator('tbody tr')).toHaveCount(1)
  await expect(stat(page, '涉及管理员')).toHaveText('1')
  await expect(table(page)).toContainText('调整药品库存')
  for (const query of ['林知远', 'ADM-001', 'AUD-20261114-001', '调整药品库存']) {
    await page.getByLabel('审计日志关键词').fill(query)
    await expect(table(page)).toContainText('MED-001')
  }
  await page.getByLabel('审计日志关键词').fill('找不到的操作')
  await expect(page.getByRole('heading', { name: '暂无符合条件的日志' })).toBeVisible()
  await expect(stat(page, '日志总数')).toHaveText('0')
  await expect(page.getByRole('button', { name: '下一页', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: '重置筛选', exact: true }).first().click()
  await expect(page.getByLabel('业务模块')).toHaveValue('全部模块')
  await expect(page.getByLabel('审计日志关键词')).toHaveValue('')
  await expect(stat(page, '日志总数')).toHaveText('28')
})

test('日期含首尾业务日，缺失或倒置不展示误导性日志', async ({ page }) => {
  await page.getByLabel('开始日期').fill('2026-11-14')
  await expect(stat(page, '日志总数')).toHaveText('4')
  await expect(table(page).locator('tbody tr').first()).toContainText('2026-11-14 09:59:59')
  await page.getByLabel('开始日期').fill('2026-11-06')
  await expect(stat(page, '日志总数')).toHaveText('36')
  await page.getByLabel('开始日期').fill('2026-11-15')
  await expect(page.getByRole('alert')).toContainText('开始日期不能晚于结束日期')
  await expect(page.getByRole('heading', { name: '请修正日期范围' })).toBeVisible()
  await expect(table(page).locator('tbody tr')).toHaveCount(0)
  await page.getByLabel('开始日期').fill('')
  await expect(page.getByRole('alert')).toContainText('请选择完整')
  await page.getByRole('button', { name: '重置筛选' }).first().click()
  await expect(page.getByLabel('开始日期')).toHaveValue('2026-11-08')
  await expect(page.getByRole('alert')).toHaveCount(0)
})

test('按操作时间倒序分页，刷新保留当前页而筛选回到第一页', async ({ page }) => {
  const times = await table(page).locator('time').evaluateAll(elements => elements.map(element => element.getAttribute('datetime')!))
  expect(times).toEqual([...times].sort().reverse())
  await page.getByRole('button', { name: '下一页', exact: true }).click()
  const secondPage = await table(page).locator('tbody').innerText()
  await expect(page.getByLabel('日志分页')).toContainText('2 / 3')
  await page.getByRole('button', { name: '刷新日志' }).click()
  await expect(page.getByLabel('日志分页')).toContainText('2 / 3')
  await expect(table(page).locator('tbody')).toHaveText(secondPage, { useInnerText: true })
  await page.getByRole('button', { name: '下一页', exact: true }).click()
  await expect(table(page).locator('tbody tr')).toHaveCount(8)
  await expect(page.getByRole('button', { name: '下一页', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: '上一页', exact: true }).click()
  await expect(page.getByLabel('日志分页')).toContainText('2 / 3')
  await page.getByLabel('审计日志关键词').fill('MED-001')
  await expect(page.getByLabel('日志分页')).toContainText('1 / 1')
  await expect(table(page).locator('tbody tr')).toHaveCount(1)
})

test('行与键盘打开详情，刷新同步抽屉并保留筛选，关闭恢复焦点', async ({ page }) => {
  await page.getByLabel('业务模块').selectOption('药品库存')
  await page.getByLabel('审计日志关键词').fill('MED-001')
  const row = table(page).locator('tbody tr').first()
  await row.focus()
  await row.press('Enter')
  await expect(drawer(page)).toBeVisible()
  await expect(drawer(page)).toContainText('AUD-20261114-001')
  await expect(drawer(page)).toContainText('ADM-001')
  await expect(drawer(page)).toContainText('保留现有库存锁定')
  await drawer(page).getByRole('button', { name: '刷新日志' }).click()
  await expect(drawer(page).getByRole('status')).toContainText('已刷新演示日志')
  await expect(drawer(page)).toContainText('MED-001')
  await page.keyboard.press('Escape')
  await expect(drawer(page)).not.toBeVisible()
  await expect(row).toBeFocused()
  await expect(page.getByLabel('业务模块')).toHaveValue('药品库存')
  await expect(page.getByLabel('审计日志关键词')).toHaveValue('MED-001')
  await row.press('Space')
  await expect(drawer(page)).toBeVisible()
  await drawer(page).getByRole('button', { name: '关闭日志详情' }).click()
  await expect(drawer(page)).not.toBeVisible()
  await row.click()
  await expect(drawer(page)).toBeVisible()
  await page.mouse.click(10, 300)
  await expect(drawer(page)).not.toBeVisible()
})

test('复制两种编号成功反馈显示在抽屉内，失败时提供手动复制内容', async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await table(page).locator('tbody tr').first().getByRole('button').click()
  await drawer(page).getByRole('button', { name: '复制日志编号', exact: true }).click()
  await expect(drawer(page).getByRole('status')).toContainText('日志编号已复制')
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe('AUD-20261114-001')
  await drawer(page).getByRole('button', { name: '复制业务编号', exact: true }).click()
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe('MED-001')
  await page.evaluate(() => Object.defineProperty(navigator.clipboard, 'writeText', { configurable: true, value: () => Promise.reject(new Error('denied')) }))
  await drawer(page).getByRole('button', { name: '复制业务编号', exact: true }).click()
  await expect(drawer(page).getByRole('status')).toContainText('请手动复制业务编号：MED-001')
})

