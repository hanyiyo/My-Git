import { test, expect, type Page } from '@playwright/test'
import { readFile } from 'node:fs/promises'

const url = '/prototype/admin-home?module=%E5%8C%BB%E7%96%97%E8%AE%BF%E9%97%AE%E5%AE%A1%E6%A0%B8'
const drawer = (page: Page) => page.getByRole('complementary', { name: '医疗访问详情' })
const content = (page: Page) => page.getByRole('dialog', { name: '授权医疗内容', exact: true })
async function request(page: Page, scope = 'RECORD', id = 'APT-M001') {
  await page.getByRole('row').filter({ hasText: id }).getByRole('button', { name: '查看详情' }).click()
  await drawer(page).getByRole('button', { name: '申请访问', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '申请医疗访问' })
  await dialog.getByLabel('本次访问范围').selectOption(scope)
  await dialog.getByLabel('访问理由', { exact: true }).fill('核验本次预约内容展示范围')
  await dialog.getByRole('button', { name: '确认申请并查看' }).click()
  await expect(content(page)).toBeVisible()
}
async function switchActor(page: Page, id: string) {
  await page.getByText('演示场景 · 切换管理员', { exact: true }).click()
  await page.getByLabel('当前演示管理员').selectOption(id)
}

test.beforeEach(async ({ page }) => {
  await page.clock.install({ time: new Date('2026-11-14T02:00:00Z') })
  await page.goto(url)
})

