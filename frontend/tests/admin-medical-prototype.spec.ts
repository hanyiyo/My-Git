test('另一管理员撤权须再次确认，取消不改变资格，重新授予不会恢复旧授权', async ({ page }) => {
  await switchActor(page, 'ADMIN-02')
  await page.getByRole('button', { name: '资格管理', exact: true }).click()
  const permissions = page.getByRole('dialog', { name: '医疗审核资格管理' })
  await permissions.getByLabel('目标管理员').selectOption('ADMIN-01')
  await permissions.getByLabel('资格操作').selectOption('false')
  await permissions.getByRole('button', { name: '继续确认撤权' }).click()
  await expect(permissions.getByRole('alert')).toContainText('资格变更理由')
  await permissions.getByLabel('资格变更理由').fill('演示撤销当前审核职责')
  await permissions.getByRole('button', { name: '继续确认撤权' }).click()
  const confirm = page.getByRole('dialog', { name: '确认撤回审核资格' })
  await expect(confirm).toContainText('现有访问授权将同时失效')
  await confirm.getByRole('button', { name: '取消', exact: true }).click()
  await expect(permissions).toContainText('当前资格：已获审核资格')
  await permissions.getByRole('button', { name: '继续确认撤权' }).click()
  await confirm.getByRole('button', { name: '确认撤回资格' }).click()
  await page.getByRole('button', { name: '资格管理', exact: true }).click()
  await permissions.getByLabel('目标管理员').selectOption('ADMIN-01')
  await expect(permissions).toContainText('当前资格：未获审核资格')
  await permissions.getByLabel('资格变更理由').fill('重新分配审核职责')
  await permissions.getByRole('button', { name: '保存审核资格' }).click()
  await page.getByLabel('当前演示管理员').selectOption('ADMIN-01')
  await expect(page.getByLabel('当前审核资格')).toContainText('已获审核资格')
  await page.getByRole('tab', { name: '我的访问记录' }).click()
  await page.getByLabel('授权状态').selectOption('有效')
  await expect(page.getByRole('heading', { name: '暂无符合条件的访问记录' })).toBeVisible()
})

