test('附件授权仅展示附件，预览下载均留记录，下载为实际PNG演示文件', async ({ page }) => {
  await request(page, 'ATTACHMENTS')
  await expect(content(page).locator('.medical-entry')).toHaveCount(1)
  await expect(content(page).getByText('演示材料：', { exact: false })).toHaveCount(0)
  await content(page).getByRole('button', { name: '预览附件' }).click()
  await expect(content(page).getByRole('img', { name: '复查资料示例.png' })).toBeVisible()
  const filePromise = page.waitForEvent('download')
  await content(page).getByRole('button', { name: '下载附件' }).click()
  const file = await filePromise
  expect(file.suggestedFilename()).toBe('复查资料示例.png')
  const filePath = await file.path()
  expect(filePath).toBeTruthy()
  const bytes = await readFile(filePath!)
  expect(bytes.subarray(0, 8).toString('hex')).toBe('89504e470d0a1a0a')
  await content(page).getByRole('button', { name: '关闭授权内容' }).click()
  await expect(drawer(page).getByLabel('访问操作记录')).toContainText('预览医疗附件')
  await expect(drawer(page).getByLabel('访问操作记录')).toContainText('下载医疗附件')
  await expect(page.getByRole('img', { name: '复查资料示例.png' })).toHaveCount(0)
})

test('限制和解除需填写理由并确认，保留原文与两次处理历史', async ({ page }) => {
  await request(page, 'ALL')
  const entry = content(page).locator('.medical-entry').filter({ hasText: '患者材料 · 版本 1' })
  const original = await entry.locator('p').textContent()
  await entry.getByRole('button', { name: '限制展示', exact: true }).click()
  const action = page.getByRole('dialog', { name: '确认内容处理' })
  await action.getByRole('button', { name: '确认限制展示' }).click()
  await expect(action.getByRole('alert')).toContainText('操作理由')
  await action.getByRole('button', { name: '取消', exact: true }).click()
  await expect(entry.getByText('正常展示', { exact: true })).toBeVisible()
  await entry.getByRole('button', { name: '限制展示', exact: true }).click()
  await action.getByLabel('操作理由').fill('展示范围需人工复核')
  await action.getByRole('button', { name: '确认限制展示' }).click()
  await expect(entry.getByText('已限制展示', { exact: true })).toBeVisible()
  await expect(entry.locator('p')).toHaveText(original!)
  await entry.getByRole('button', { name: '解除限制', exact: true }).click()
  await action.getByRole('button', { name: '确认解除限制' }).click()
  await expect(action.getByRole('alert')).toContainText('操作理由')
  await action.getByLabel('操作理由').fill('复核完成，恢复正常展示')
  await action.getByRole('button', { name: '确认解除限制' }).click()
  await expect(entry.getByText('正常展示', { exact: true })).toBeVisible()
  await expect(entry.locator('p')).toHaveText(original!)
  await content(page).getByRole('button', { name: '关闭授权内容' }).click()
  const history = drawer(page).getByLabel('访问操作记录')
  await expect(history).toContainText('限制内容展示')
  await expect(history).toContainText('解除内容限制')
  await expect(history).not.toContainText(original!)
})

test('普通关闭保留有效授权，重复读取留审计，主动结束后必须重新申请', async ({ page }) => {
  await request(page)
  await content(page).getByRole('button', { name: '关闭授权内容' }).click()
  await drawer(page).getByRole('button', { name: '查看授权内容', exact: true }).click()
  await expect(content(page).getByText('演示材料：', { exact: false })).toBeVisible()
  await content(page).getByRole('button', { name: '结束本次访问', exact: true }).click()
  const end = page.getByRole('dialog', { name: '结束本次访问', exact: true })
  await end.getByLabel('操作理由').fill('本次核验完成')
  await end.getByRole('button', { name: '确认结束访问' }).click()
  await expect(content(page).getByRole('alert')).toContainText('本次访问已失效')
  await expect(page.getByText('演示材料：', { exact: false })).toHaveCount(0)
  await content(page).getByRole('button', { name: '关闭授权内容' }).click()
  await expect(drawer(page)).toContainText('已撤回')
  await expect(drawer(page).getByLabel('访问操作记录').getByText('读取医疗内容', { exact: true })).toHaveCount(2)
  await expect(drawer(page).getByRole('button', { name: '查看授权内容', exact: true })).toHaveCount(0)
  await drawer(page).getByRole('button', { name: '重新申请访问' }).click()
  await expect(page.getByRole('dialog', { name: '申请医疗访问' }).getByLabel('访问理由', { exact: true })).toHaveValue('')
})

test('真实时钟到期清空正文预览并关闭待确认操作，释放附件预览地址', async ({ page }) => {
  await request(page, 'ALL')
  await content(page).getByRole('button', { name: '预览附件' }).click()
  const image = content(page).getByRole('img', { name: '复查资料示例.png' })
  await expect(image).toBeVisible()
  const blobUrl = await image.getAttribute('src')
  await content(page).locator('.medical-entry').first().getByRole('button', { name: '限制展示', exact: true }).click()
  const action = page.getByRole('dialog', { name: '确认内容处理' })
  await action.getByLabel('操作理由').fill('未提交的操作')
  await page.clock.fastForward(30 * 60000)
  await expect(action).not.toBeVisible()
  await expect(content(page).getByRole('alert')).toContainText('本次访问已失效')
  await expect(page.getByText('演示材料：', { exact: false })).toHaveCount(0)
  await expect(image).toHaveCount(0)
  expect(await page.evaluate(async link => { try { await fetch(link!); return false } catch { return true } }, blobUrl)).toBe(true)
  await content(page).getByRole('button', { name: '重新申请访问' }).click()
  await expect(page.getByRole('dialog', { name: '申请医疗访问' }).getByLabel('访问理由', { exact: true })).toHaveValue('')
})

