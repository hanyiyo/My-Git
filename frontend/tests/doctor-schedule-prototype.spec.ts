import { test, expect, type Page } from '@playwright/test'

const path = '/prototype/doctor-home/schedules'
const detail = (page: Page) => page.getByRole('complementary', { name: '所选日期详情' })
const today = (page: Page) => page.getByRole('region', { name: '今日排班', exact: true })
const day = (page: Page, date: string) => page.locator(`[data-calendar-date="${date}"]`)
async function snapshot(page: Page) {
  await expect.poll(() => page.evaluate(() => {
    const raw = localStorage.getItem('medical-reception-prototype-v1')
    if (!raw) return 'missing'
    try { JSON.parse(raw); return 'ready' } catch { return 'invalid' }
  })).toBe('ready')
  return page.evaluate(() => JSON.parse(localStorage.getItem('medical-reception-prototype-v1')!))
}
async function select(page: Page, date = '2026-11-16', mode: 'all' | 'online' | 'offline' = 'all') {
  await page.goto(`${path}?month=${date.slice(0, 7)}&date=${date}&mode=${mode}`)
  await expect(detail(page)).toBeVisible()
}
async function apply(page: Page, date = '2026-11-16', mode: 'all' | 'online' | 'offline' = 'online') {
  await select(page, date, mode)
  await detail(page).getByRole('button', { name: '申请停诊', exact: true }).first().click()
  await expect(page.getByRole('region', { name: '本场停诊申请' })).toBeVisible()
}
async function review(page: Page, text = '参加院内业务培训，申请本场停诊。') {
  await page.getByRole('textbox', { name: '停诊原因' }).fill(text)
  await page.getByRole('button', { name: '核对并提交申请' }).click()
  return page.getByRole('dialog', { name: '核对停诊申请' })
}
async function submit(page: Page) {
  const dialog = await review(page)
  await dialog.getByRole('checkbox').check()
  await dialog.getByRole('button', { name: '确认提交', exact: true }).click()
  await expect(dialog).not.toBeVisible()
}
async function setDateTime(page: Page, date: string, time: string) {
  await page.getByRole('button', { name: '演示设置', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '原型演示设置' })
  await dialog.getByLabel('审批演示日期', { exact: true }).fill(date)
  await dialog.getByLabel('联动演示时间').fill(time)
  await dialog.getByRole('button', { name: '应用审批演示日期时间' }).click()
  await dialog.getByRole('button', { name: '完成设置' }).click()
}

