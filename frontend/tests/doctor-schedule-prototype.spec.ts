test('存储拒绝保留原因并重试，旧接诊快照升级保留医疗草稿', async ({ page }) => {
  await page.goto('/prototype/doctor-home/reception')
  await page.getByRole('button', { name: '叫号并开始接诊' }).click()
  await page.getByRole('textbox', { name: '主诉', exact: true }).fill('需要保留的旧接诊草稿')
  await expect(page.locator('.rd-editor-footer')).toContainText('已保存')
  await page.evaluate(() => { const key = 'medical-reception-prototype-v1', data = JSON.parse(localStorage.getItem(key)!); delete data.schedules; delete data.applications; localStorage.setItem(key, JSON.stringify(data)) })
  await apply(page)
  const dialog = await review(page, '浏览器恢复后仍需保留的申请原因')
  await page.evaluate(() => { (window as any).scheduleOriginalSet = Storage.prototype.setItem; Storage.prototype.setItem = function () { throw new DOMException('blocked', 'QuotaExceededError') } })
  await dialog.getByRole('checkbox').check()
  await dialog.getByRole('button', { name: '确认提交', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('当前操作未保存')
  await expect(dialog).toContainText('浏览器恢复后仍需保留的申请原因')
  await page.evaluate(() => { Storage.prototype.setItem = (window as any).scheduleOriginalSet })
  await dialog.getByRole('button', { name: '确认提交', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  expect((await snapshot(page)).visits.find((v: any) => v.id === 'demo-001').draft.complaint).toBe('需要保留的旧接诊草稿')
})

test('两个标签同时提交同场申请，只保留一份并说明冲突', async ({ page, context }) => {
  await apply(page)
  const other = await context.newPage(); await apply(other)
  const first = await review(page, '第一标签申请'), second = await review(other, '第二标签申请')
  await first.getByRole('checkbox').check(); await second.getByRole('checkbox').check()
  await page.evaluate(() => new Promise<void>(ready => { void navigator.locks.request('medical-reception-prototype-v1', () => new Promise<void>(release => { (window as any).releaseScheduleLock = release; ready() })) }))
  await Promise.all([first.getByRole('button', { name: '确认提交', exact: true }).click(), second.getByRole('button', { name: '确认提交', exact: true }).click()])
  await page.evaluate(() => (window as any).releaseScheduleLock())
  await expect.poll(async () => (await snapshot(page)).applications.filter((a: any) => a.scheduleId === '2026-11-16-pm').length).toBe(1)
  await expect.poll(async () => [...await page.getByRole('alert').allTextContents(), ...await other.getByRole('alert').allTextContents()].join(' ')).toContain('已有未结束申请')
})

