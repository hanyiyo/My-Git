test('24小时边界允许恰好截止，超过截止不可申请，审批自动过期', async ({ page }) => {
  await page.clock.install({ time: new Date('2026-11-12T06:00:00+08:00') })
  await page.clock.pauseAt(new Date('2026-11-12T06:00:01+08:00'))
  await page.goto(path)
  await setDateTime(page, '2026-11-12', '14:00')
  await apply(page, '2026-11-13', 'online')
  await submit(page)
  const request = (await snapshot(page)).applications.find((a: any) => a.scheduleId === '2026-11-13-pm')
  expect(request.deadline).toBe(Date.parse('2026-11-12T14:00:00+08:00'))
  await setDateTime(page, '2026-11-12', '14:01')
  await expect(page.getByRole('region', { name: '本场停诊申请' })).toContainText('已过期')
  await expect(page.getByRole('region', { name: '本场停诊申请' })).toContainText('须至少提前 24 小时')
  await select(page, '2026-11-13', 'online')
  await expect(detail(page).getByRole('button', { name: '申请停诊', exact: true })).toBeDisabled()
  await expect(detail(page)).not.toContainText('暂停新增挂号')
})

