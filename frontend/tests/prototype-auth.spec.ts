import { test, expect } from '@playwright/test'

for (const variant of ['A', 'B', 'C']) {
  test(`prototype ${variant} preserves all three roles and registration behavior`, async ({ page }, testInfo) => {
    await page.setViewportSize({ width: 1440, height: 1050 })
    const requests: string[] = []
    await page.route('**/api/**', route => {
      requests.push(route.request().url())
      return route.fulfill({ status: 401, contentType: 'application/json', body: '{}' })
    })
    await page.goto(`/prototype/auth?variant=${variant}`)
    await expect(page.getByRole('navigation', { name: '原型方案切换' })).toBeVisible()
    await expect(page.getByAltText('模拟图形验证码')).toBeVisible()
    const image = await page.getByAltText('模拟图形验证码').getAttribute('src')
    await page.getByLabel('图形验证码', { exact: true }).fill('preview')
    await page.getByRole('button', { name: '换一张验证码' }).click()
    await expect(page.getByAltText('模拟图形验证码')).not.toHaveAttribute('src', image!)
    await expect(page.getByLabel('图形验证码', { exact: true })).toHaveValue('')
    await page.screenshot({ path: testInfo.outputPath(`variant-${variant}-desktop.png`), fullPage: true })

    for (const role of ['患者端', '医生端', '管理员端']) {
      await page.getByRole('tab', { name: new RegExp(role) }).click()
      await expect(page.getByRole('tab', { name: new RegExp(role) })).toHaveAttribute('aria-selected', 'true')
      if (role === '管理员端') {
        await expect(page.getByRole('tab', { name: /^注册/ })).toHaveCount(0)
        await expect(page.getByText('管理员账号只能由管理员在后台创建。')).toBeVisible()
      }
      await page.getByRole('button', { name: '填入演示账号' }).click()
      await page.getByRole('button', { name: '显示密码', exact: true }).click()
      await expect(page.getByLabel('密码', { exact: true })).toHaveAttribute('type', 'text')
      await page.getByRole('button', { name: '隐藏密码', exact: true }).click()
      await page.getByLabel('记住本次演示').uncheck()
      await page.getByRole('button', { name: '忘记密码？' }).click()
      await expect(page.getByRole('status')).toContainText('未接入找回密码流程')
      // The captcha is a layout mock: preserve the original login predicate without adding validation.
      await page.getByRole('button', { name: '进入演示工作台' }).click()
      await expect(page.getByRole('heading', { name: `${role}工作台已打开` })).toBeVisible()
      await page.getByRole('button', { name: '退出体验' }).click()
      await expect(page.getByRole('heading', { name: '欢迎回来' })).toBeVisible()
    }

    await page.getByRole('tab', { name: /医生端/ }).click()
    await page.getByRole('tab', { name: /^注册/ }).click()
    await page.getByRole('tab', { name: /管理员端/ }).click()
    await expect(page.getByRole('tab', { name: /^注册/ })).toHaveCount(0)
    await expect(page.getByLabel('确认密码', { exact: true })).toHaveCount(0)
    await expect(page.getByRole('button', { name: '创建演示账户', exact: true })).toHaveCount(0)
    await expect(page.getByRole('heading', { name: '欢迎回来' })).toBeVisible()
    await page.getByRole('tab', { name: /医生端/ }).click()
    await page.getByLabel('账号', { exact: true }).fill('')
    await page.getByRole('button', { name: '进入演示工作台' }).click()
    await expect(page.getByRole('status')).toHaveText('请先填写账号和密码。')
    await page.getByRole('tab', { name: /^注册/ }).click()
    await expect(page.getByLabel('图形验证码', { exact: true })).toHaveCount(0)
    await page.getByLabel('账号', { exact: true }).fill('doctor-prototype')
    await page.getByLabel('显示名称').fill('林医生')
    await page.getByLabel('密码', { exact: true }).fill('short')
    await page.getByLabel('确认密码', { exact: true }).fill('short')
    await page.getByRole('button', { name: '创建演示账户', exact: true }).click()
    await expect(page.getByRole('status')).toHaveText('演示密码至少需要 8 位。')
    await page.getByLabel('密码', { exact: true }).fill('prototype-password')
    await page.getByRole('button', { name: '创建演示账户', exact: true }).click()
    await expect(page.getByRole('status')).toHaveText('两次输入的密码不一致。')
    await page.getByLabel('确认密码', { exact: true }).fill('prototype-password')
    await page.screenshot({ path: testInfo.outputPath(`variant-${variant}-register.png`), fullPage: true })
    await page.getByRole('button', { name: '创建演示账户', exact: true }).click()
    await expect(page.getByRole('status')).toContainText('注册成功')
    await expect(page.getByLabel('账号', { exact: true })).toHaveValue('doctor-prototype')
    await page.getByRole('button', { name: '进入演示工作台' }).click()
    await expect(page.getByRole('heading', { name: '医生端工作台已打开' })).toBeVisible()
    expect(requests.filter(url => !/\/auth\/(csrf|refresh)$/.test(url))).toEqual([])
  })

  test(`prototype ${variant} remains usable on a narrow screen`, async ({ page }, testInfo) => {
    await page.setViewportSize({ width: 390, height: 844 })
    await page.route('**/api/**', route => route.fulfill({ status: 401, contentType: 'application/json', body: '{}' }))
    await page.goto(`/prototype/auth?variant=${variant}`)
    await expect(page.getByLabel('账号', { exact: true })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await page.getByRole('tab', { name: /管理员端/ }).click()
    await expect(page.getByRole('tab', { name: /^注册/ })).toHaveCount(0)
    await expect(page.getByText('管理员账号只能由管理员在后台创建。')).toBeVisible()
    await page.getByRole('button', { name: '填入演示账号' }).click()
    await page.getByRole('button', { name: '换一张验证码' }).click()
    await page.screenshot({ path: testInfo.outputPath(`variant-${variant}-mobile.png`), fullPage: true })
    await page.getByRole('button', { name: '进入演示工作台' }).click()
    await expect(page.getByRole('heading', { name: '管理员端工作台已打开' })).toBeVisible()
    await page.getByRole('button', { name: '退出体验' }).click()
    await page.getByRole('tab', { name: /患者端/ }).click()
    await page.getByRole('tab', { name: /^注册/ }).click()
    await expect(page.getByLabel('确认密码', { exact: true })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  })
}

test('prototype variants preserve form/session state, URL and keyboard editing', async ({ page }) => {
  await page.route('**/api/**', route => route.fulfill({ status: 401, contentType: 'application/json', body: '{}' }))
  await page.goto('/prototype/auth?keep=1')
  await expect(page.getByRole('button', { name: '方案 A：深蓝分栏' })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('tab', { name: /医生端/ }).click()
  await page.getByRole('tab', { name: /^注册/ }).click()
  await page.getByLabel('账号', { exact: true }).fill('shared-state')
  await page.getByLabel('密码', { exact: true }).fill('prototype-password')
  await page.getByLabel('显示名称').fill('林医生')
  await page.getByLabel('确认密码', { exact: true }).fill('prototype-password')
  await page.getByRole('button', { name: '下一方案' }).click()
  await expect(page).toHaveURL(/variant=B/)
  await expect(page).toHaveURL(/keep=1/)
  await expect(page.getByLabel('账号', { exact: true })).toHaveValue('shared-state')
  await expect(page.getByLabel('确认密码', { exact: true })).toHaveValue('prototype-password')
  await page.getByLabel('账号', { exact: true }).press('ArrowRight')
  await expect(page).toHaveURL(/variant=B/)
  await page.getByLabel('确认密码', { exact: true }).press('ArrowLeft')
  await expect(page).toHaveURL(/variant=B/)
  await page.locator('body').click({ position: { x: 1, y: 1 } })
  await page.keyboard.press('ArrowRight')
  await expect(page).toHaveURL(/variant=C/)
  await expect(page.getByLabel('显示名称')).toHaveValue('林医生')
  await page.getByRole('button', { name: '创建演示账户', exact: true }).click()
  await page.getByRole('button', { name: '进入演示工作台' }).click()
  await page.getByRole('button', { name: '下一方案' }).click()
  await expect(page).toHaveURL(/variant=A/)
  await expect(page.getByRole('heading', { name: '医生端工作台已打开' })).toBeVisible()
  await page.getByRole('button', { name: '上一方案' }).click()
  await expect(page).toHaveURL(/variant=C/)
  await page.reload()
  await expect(page.getByRole('button', { name: '方案 C：服务工作台' })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByLabel('账号', { exact: true })).toHaveValue('')
  await page.goto('/prototype/auth?variant=invalid')
  await expect(page.getByRole('button', { name: '方案 A：深蓝分栏' })).toHaveAttribute('aria-pressed', 'true')
})
