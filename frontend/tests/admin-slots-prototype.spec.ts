import { test, expect } from '@playwright/test'

test('管理员号源工作台默认展示今天已发布库存和完整筛选', async ({ page }) => {
  const apiRequests: string[] = []
  page.on('request', request => { if (request.url().includes('/api/')) apiRequests.push(request.url()) })
  await page.goto('/prototype/admin-slots')
  await expect(page.getByRole('heading', { name: '号源管理工作台' })).toBeVisible()
  await expect(page.getByRole('region', { name: '号源库存表' })).toBeVisible()
  await expect(page.getByRole('region', { name: '号源库存表' })).toContainText('周宁')
  await expect(page.getByRole('region', { name: '号源库存表' })).toContainText('林牧')
  await expect(page.getByRole('region', { name: '号源库存表' })).not.toContainText('郭妤')
  await expect(page.getByLabel('号源状态')).toHaveValue('PUBLISHED')
  for (const label of ['开始日期', '结束日期', '号源门诊时段', '号源服务方式', '号源医生', '号源科室', '号源状态', '搜索号源']) await expect(page.getByLabel(label)).toBeVisible()
  expect(apiRequests).toEqual([])
})

test('号源状态和日期筛选能查看只读场次并保留库存口径', async ({ page }) => {
  await page.goto('/prototype/admin-slots')
  await page.getByLabel('号源状态').selectOption('ALL')
  await page.getByLabel('开始日期').fill('2026-11-14')
  await page.getByLabel('结束日期').fill('2026-11-18')
  const table = page.getByRole('region', { name: '号源库存表' })
  await expect(table).toContainText('草稿')
  await expect(table).toContainText('暂停新增')
  await expect(table).toContainText('已替诊')
  await expect(table).toContainText('20')
  await expect(table).toContainText('临时占号')
})

test('有患者承诺的号源详情只读，并可跳转对应排班', async ({ page }) => {
  await page.goto('/prototype/admin-slots')
  const row = page.getByRole('row').filter({ hasText: '周宁' }).first()
  await row.click()
  const drawer = page.getByRole('complementary', { name: '号源详情' })
  await expect(drawer).toContainText('已挂号')
  await expect(drawer).toContainText('临时占号')
  await expect(drawer).toContainText('已有患者承诺')
  await expect(drawer.getByRole('button', { name: '调整号源' })).toBeDisabled()
  await drawer.getByRole('button', { name: '查看排班' }).click()
  await expect(page).toHaveURL(/\/prototype\/admin-schedules\?date=2026-11-13/)
})

test('无患者承诺的已发布号源可以在确认表单中调整容量并反馈结果', async ({ page }) => {
  await page.goto('/prototype/admin-slots')
  await page.getByLabel('号源状态').selectOption('ALL')
  await page.getByLabel('开始日期').fill('2026-11-15')
  await page.getByLabel('结束日期').fill('2026-11-15')
  await page.getByRole('row').filter({ hasText: '郭妤' }).click()
  const drawer = page.getByRole('complementary', { name: '号源详情' })
  await drawer.getByRole('button', { name: '调整号源' }).click()
  const dialog = page.getByRole('dialog', { name: '调整号源' })
  await expect(dialog).toContainText('当前总号源')
  await dialog.getByLabel('新总号源').fill('0')
  await dialog.getByRole('button', { name: '确认调整' }).click()
  await expect(dialog.getByRole('alert')).toContainText('大于或等于 1 的整数')
  await expect(dialog).toBeVisible()
  await dialog.getByLabel('新总号源').fill('14')
  await dialog.getByRole('button', { name: '确认调整' }).click()
  await expect(page.getByRole('region', { name: '号源库存表' })).toContainText('14')
  await expect(drawer.getByRole('status')).toContainText('总号源已从 12 调整为 14')
})

