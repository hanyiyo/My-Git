import { test, expect } from '@playwright/test'

test('通知导航、阅读、红点与新闻深链接保持一致，且不调用业务接口', async ({ page }) => {
  const requests: string[] = []
  page.on('request', request => { if (request.url().includes('/api/')) requests.push(request.url()) })
  await page.goto('/prototype/patient-home?variant=A')
  const count = page.getByTestId('system-unread-count')
  const initial = Number(await count.textContent())
  await page.getByRole('navigation', { name: '顶部快捷导航' }).getByRole('button', { name: '站内通知', exact: true }).click()
  await expect(page).toHaveURL(/notifications\?tab=system/)
  const center = page.getByTestId('notifications-page')
  await expect(center.getByRole('button', { name: '清空', exact: true })).toBeEnabled()
  await expect(count).toHaveText(String(initial))
  await page.screenshot({ path: '../.runtime/notifications-system-desktop.png', fullPage: true })
  const suspension = page.getByTestId('notice-suspension')
  await suspension.getByRole('button', { name: /^阅读/ }).click()
  const detail = page.getByRole('dialog', { name: '门诊停诊，请留意就诊安排', exact: true })
  await expect(detail).toContainText('订单取消不代表退款已经到账')
  await expect(detail.getByRole('button', { name: '查看订单', exact: true })).toBeVisible()
  await expect(detail.getByRole('button', { name: /重新挂号|取消挂号|立即付款|接受替诊/ })).toHaveCount(0)
  await expect(count).toHaveText(String(initial - 1))
  await page.keyboard.press('Escape')
  await expect(suspension).not.toHaveClass(/unread/)
  await expect(center.getByRole('region', { name: '重要提醒', exact: true }).getByTestId('notice-suspension')).toBeVisible()
  await center.getByRole('button', { name: '未读', exact: true }).click()
  await expect(suspension).toHaveCount(0)
  await center.getByRole('button', { name: '全部标为已读' }).click()
  await expect(center).toContainText('暂无未读通知')
  await expect(count).toHaveCount(0)
  await expect(page.getByTestId('notification-unread-dot')).toHaveCount(0)
  await page.getByRole('navigation', { name: '顶部快捷导航' }).getByRole('button', { name: '首页', exact: true }).click()
  await page.getByRole('button', { name: /秋冬季门诊就诊温馨提示/ }).click()
  await expect(page).toHaveURL(/tab=news&notice=news-1/)
  await expect(page.getByRole('dialog', { name: '秋冬季门诊就诊温馨提示', exact: true })).toBeVisible()
  await expect(page.getByRole('dialog').getByRole('button', { name: '查看订单' })).toHaveCount(0)
  await page.keyboard.press('Escape')
  await expect(center.getByRole('tab', { name: /医院新闻/ })).toHaveAttribute('aria-selected', 'true')
  await page.getByRole('navigation', { name: '临时工作区标签' }).getByLabel('关闭站内通知').click()
  await page.getByRole('button', { name: '查看站内通知', exact: true }).click()
  await expect(count).toHaveCount(0)
  await page.reload()
  await expect(count).toHaveText(String(initial))
  expect(requests).toEqual([])
})

test('新闻已读与清空只影响当前标签，未读筛选下清空仍包括已读', async ({ page }) => {
  await page.goto('/prototype/patient-home/notifications?tab=news')
  const center = page.getByTestId('notifications-page')
  await expect(center.getByRole('button', { name: '清空', exact: true })).toBeEnabled()
  const systemCount = await page.getByTestId('system-unread-count').textContent()
  await center.getByRole('button', { name: '全部标为已读' }).click()
  await center.getByRole('button', { name: '未读', exact: true }).click()
  await expect(center).toContainText('暂无未读通知')
  await expect(page.getByTestId('system-unread-count')).toHaveText(systemCount!)
  await center.getByRole('button', { name: '清空', exact: true }).click()
  const confirm = page.getByRole('dialog', { name: '确认清空当前标签下的 5 条通知？', exact: true })
  await expect(confirm).toContainText('包括已读和未读，不受当前筛选影响')
  await expect(confirm.getByRole('button', { name: '取消', exact: true })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(center.getByRole('button', { name: '清空', exact: true })).toBeFocused()
  await center.getByRole('button', { name: '清空', exact: true }).click()
  await confirm.getByRole('button', { name: '确认清空' }).click()
  await expect(center).toContainText('暂无通知')
  await center.getByRole('tab', { name: /系统通知/ }).click()
  await expect(page.getByTestId('notice-suspension')).toBeVisible()
  await expect(page.getByTestId('system-unread-count')).toHaveText(systemCount!)
  const total = await center.locator('.ph-notice-row').count()
  await center.getByRole('button', { name: '未读', exact: true }).click()
  await center.getByRole('button', { name: '清空', exact: true }).click()
  const clearSystem = page.getByRole('dialog', { name: `确认清空当前标签下的 ${total} 条通知？`, exact: true })
  await expect(clearSystem).toContainText('包括已读和未读')
  await clearSystem.getByRole('button', { name: '确认清空', exact: true }).click()
  await expect(page.getByTestId('notification-unread-dot')).toHaveCount(0)
  await expect(center).toContainText('暂无通知')
  await page.getByRole('link', { name: '智能医疗问诊预约系统首页' }).click()
  await page.getByRole('button', { name: /秋冬季门诊就诊温馨提示/ }).click()
  await expect(page.getByRole('dialog')).toContainText('该通知已删除或暂不可用')
})

test('删除重要通知需确认，删除详情后关闭，订单和原文不受影响', async ({ page }) => {
  await page.goto('/prototype/patient-home/notifications?tab=system&notice=substitution')
  const detail = page.getByRole('dialog', { name: '预约医生已调整，原预约继续有效', exact: true })
  await expect(detail).toContainText('无需确认接受替诊')
  await detail.getByRole('button', { name: '删除通知', exact: true }).click()
  const confirm = page.getByRole('dialog', { name: '确认删除这条通知？', exact: true })
  await expect(confirm).toContainText('删除后仍可在我的挂号查看相关业务状态')
  await expect(confirm.getByRole('button', { name: '取消', exact: true })).toBeFocused()
  await confirm.getByRole('button', { name: '取消', exact: true }).click()
  await expect(detail.getByRole('button', { name: '删除通知', exact: true })).toBeFocused()
  await detail.getByRole('button', { name: '查看订单', exact: true }).click()
  await expect(page).toHaveURL(/orders\?status=.*&order=future-offline-booking/)
  await expect(page.locator('[data-order-id="future-offline-booking"]')).toHaveAttribute('data-selected', 'true')
  await expect(page.locator('[data-order-id="future-offline-booking"]')).toContainText('林牧')
  await page.getByRole('button', { name: '查看站内通知', exact: true }).click()
  await page.getByTestId('notice-substitution').getByRole('button', { name: /^阅读/ }).click()
  await detail.getByRole('button', { name: '删除通知', exact: true }).click()
  await confirm.getByRole('button', { name: '确认删除', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByTestId('notice-substitution')).toHaveCount(0)
  // A router navigation preserves in-memory deletion, unlike a full page reload.
  await page.evaluate(async () => { window.history.pushState({}, '', '/prototype/patient-home/notifications?tab=system&notice=substitution'); window.dispatchEvent(new PopStateEvent('popstate')) })
  await expect(page.getByRole('dialog')).toContainText('该通知已删除或暂不可用')
  await page.getByRole('button', { name: '返回列表', exact: true }).click()
  await page.getByRole('navigation', { name: '顶部快捷导航' }).getByRole('button', { name: '我的挂号', exact: true }).click()
  await expect(page.locator('[data-order-id="future-offline-booking"]')).toContainText('待签到')
})

test('通知失效归入时间组，停诊定位已取消订单，单条删除与已读正确更新红点', async ({ page }) => {
  await page.goto('/prototype/patient-home/notifications?tab=system')
  const center = page.getByTestId('notifications-page')
  await expect(center.getByRole('region', { name: '重要提醒', exact: true })).toBeVisible()
  await expect(center.getByRole('region', { name: '更早', exact: true }).getByTestId('notice-old-checkin')).toBeVisible()
  const count = Number(await page.getByTestId('system-unread-count').textContent())
  await page.getByTestId('notice-payment').getByRole('button', { name: /^标为已读/ }).click()
  await expect(page.getByTestId('system-unread-count')).toHaveText(String(count - 1))
  await page.getByTestId('notice-refund').getByRole('button', { name: /^删除/ }).click()
  await page.getByRole('button', { name: '确认删除', exact: true }).click()
  await expect(page.getByTestId('system-unread-count')).toHaveText(String(count - 2))
  await page.getByTestId('notice-suspension').getByRole('button', { name: /^阅读/ }).click()
  await page.getByRole('button', { name: '查看订单', exact: true }).click()
  await expect(page.locator('[data-order-id="suspended-booking"]')).toHaveAttribute('data-selected', 'true')
  await expect(page.locator('[data-order-id="suspended-booking"]')).toContainText('退款处理中')
  await page.getByRole('button', { name: '查看站内通知', exact: true }).click()
  await center.getByText('原型演示 · 虚构数据，刷新重置', { exact: true }).click()
  await center.getByLabel('通知演示状态').selectOption('expired')
  await expect(center.getByRole('region', { name: '重要提醒', exact: true })).toHaveCount(0)
  await expect(center.getByRole('region', { name: '今天', exact: true }).getByTestId('notice-checkin')).toBeVisible()
  await center.getByLabel('通知演示状态').selectOption('normal')
  await page.getByTestId('notice-checkin').getByRole('button', { name: /^阅读/ }).click()
  await page.getByRole('button', { name: '查看订单', exact: true }).click()
  await page.locator('[data-order-id="today-offline-pending"]').getByRole('button', { name: '签到', exact: true }).click()
  await page.getByRole('button', { name: '查看站内通知', exact: true }).click()
  await expect(center.getByRole('region', { name: '今天', exact: true }).getByTestId('notice-checkin')).toBeVisible()
  await expect(center.getByRole('region', { name: '重要提醒', exact: true }).getByTestId('notice-checkin')).toHaveCount(0)
})

test('通知加载失败可重试，刷新失败保留已有内容，深链接纠正分类', async ({ page }) => {
  await page.goto('/prototype/patient-home/notifications?tab=system&notice=news-adjustment&demo=error')
  const center = page.getByTestId('notifications-page')
  await expect(center.getByRole('alert')).toContainText('通知暂时加载失败')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await center.getByRole('button', { name: '重新加载', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '周末门诊服务时间调整公告', exact: true })).toBeVisible()
  await expect(page).toHaveURL(/tab=news/)
  await page.keyboard.press('Escape')
  await center.getByText('原型演示 · 虚构数据，刷新重置', { exact: true }).click()
  await center.getByLabel('通知演示状态').selectOption('refresh-error')
  await expect(center.getByRole('alert')).toContainText('已展示的内容仍可继续浏览')
  await expect(page.getByTestId('notice-news-adjustment')).toBeVisible()
  await center.getByRole('button', { name: '重新加载', exact: true }).click()
  await expect(center.getByRole('alert')).toHaveCount(0)
  await expect(center.getByRole('button', { name: '刷新', exact: true })).toBeEnabled()
  await page.screenshot({ path: '../.runtime/notifications-desktop.png', fullPage: true })
  await page.goto('/prototype/patient-home/notifications?notice=unknown')
  await expect(page.getByRole('dialog')).toContainText('该通知已删除或暂不可用')
})

test('手机通知与全屏详情无横向溢出，确认框支持键盘取消', async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 812 })
  await page.goto('/prototype/patient-home/notifications?tab=system')
  const center = page.getByTestId('notifications-page')
  await expect(center.getByRole('button', { name: '清空', exact: true })).toBeEnabled()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: '../.runtime/notifications-mobile.png', fullPage: true })
  await page.getByTestId('notice-substitution').getByRole('button', { name: /^阅读/ }).click()
  const detail = page.getByRole('dialog', { name: '预约医生已调整，原预约继续有效', exact: true })
  const box = await detail.boundingBox()
  expect(box?.width).toBe(375)
  expect(box?.height).toBe(812)
  expect(await detail.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
  await page.screenshot({ path: '../.runtime/notifications-mobile-detail.png' })
  await detail.getByRole('button', { name: '删除通知', exact: true }).click()
  const confirm = page.getByRole('dialog', { name: '确认删除这条通知？', exact: true })
  await expect(confirm.getByRole('button', { name: '取消', exact: true })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(detail).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
})
