test('两个医生标签同时编辑时检测草稿冲突，不静默覆盖', async ({ page, context }) => {
  await page.goto(doctorPath); await call(page)
  const other = await context.newPage(); await other.goto('/prototype/doctor-home/reception?patient=demo-001')
  await expect(other.getByRole('textbox', { name: '主诉', exact: true })).toBeVisible()
  await holdWrites(page)
  await Promise.all([page.getByRole('textbox', { name: '主诉', exact: true }).fill('第一标签草稿'), other.getByRole('textbox', { name: '主诉', exact: true }).fill('第二标签草稿')])
  await releaseWrites(page)
  await expect.poll(async () => (await snapshot(page)).visits.find((v: any) => v.id === 'demo-001').draftVersion).toBe(1)
  const stored = (await snapshot(page)).visits.find((v: any) => v.id === 'demo-001').draft.complaint
  const losingPage = stored === '第一标签草稿' ? other : page
  await expect(losingPage.getByRole('alert')).toContainText(/标签页.*草稿/)
  await expect(losingPage.getByRole('textbox', { name: '主诉', exact: true })).toHaveValue(stored === '第一标签草稿' ? '第二标签草稿' : '第一标签草稿')
  await losingPage.getByRole('button', { name: '重新载入草稿' }).click()
  await expect(losingPage.getByRole('textbox', { name: '主诉', exact: true })).toHaveValue(stored)
})

