import { test, expect } from '@playwright/test'

test('医生首页提供六模块框架，临时标签与继续接诊保留患者上下文', async ({ page }) => {
  const requests: string[] = []
  page.on('request', request => { if (request.url().includes('/api/')) requests.push(request.url()) })
  await page.goto('/prototype/doctor-home')
  await expect(page.getByRole('heading', { name: '上午好，许知遥医生。' })).toBeVisible()
  const nav = page.getByRole('navigation', { name: '医生端导航' })
  for (const label of ['首页', '接诊工作台', '我的排班', '申请处理', '站内通知', '个人中心']) {
    await expect(nav.getByRole('button', { name: label, exact: true })).toBeVisible()
  }
  await page.getByRole('button', { name: '进入接诊工作台', exact: true }).first().click()
  await expect(page.getByRole('heading', { name: '接诊工作台', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '叫号并开始接诊' })).toBeVisible()
  await page.getByRole('button', { name: '关闭接诊工作台标签' }).click()
  await expect(page.getByRole('heading', { name: '上午好，许知遥医生。' })).toBeVisible()
  await page.getByRole('button', { name: '收起侧栏', exact: true }).click()
  await expect(page.getByRole('button', { name: '展开侧栏', exact: true })).toHaveAttribute('aria-expanded', 'false')
  await page.getByRole('button', { name: '展开侧栏', exact: true }).click()
  expect(requests).toEqual([])
})

test('候诊可以搜索、查看上下文，替诊待办进入申请详情处理', async ({ page }) => {
  await page.goto('/prototype/doctor-home')
  await page.getByRole('textbox', { name: '搜索候诊患者' }).fill('林知夏')
  await expect(page.getByRole('button', { name: '查看林知夏详情' })).toBeVisible()
  await expect(page.getByRole('button', { name: '查看陈亦安详情' })).toHaveCount(0)
  await page.getByRole('button', { name: '查看林知夏详情' }).click()
  const detail = page.getByRole('dialog', { name: '患者详情' })
  await expect(detail).toContainText('A007')
  await page.keyboard.press('Escape')
  await expect(detail).not.toBeVisible()
  await expect(page.getByRole('button', { name: '查看林知夏详情' })).toBeFocused()
  await page.getByRole('button', { name: '查看林知夏详情' }).click()
  await detail.getByRole('button', { name: '进入接诊工作台' }).click()
  await expect(page).toHaveURL(/reception\?patient=demo-001/)
  await expect(page.getByRole('heading', { name: /林知夏/ })).toBeVisible()
  const tabs = page.getByRole('navigation', { name: '医生临时工作区标签' })
  await tabs.getByRole('button', { name: '接诊工作台', exact: true }).click()
  await expect(page.getByRole('heading', { name: /林知夏/ })).toBeVisible()
  await page.getByRole('navigation', { name: '医生端导航' }).getByRole('button', { name: '申请处理', exact: true }).click()
  await tabs.getByRole('button', { name: '接诊工作台', exact: true }).click()
  await expect(page).toHaveURL(/reception\?patient=demo-001/)
  await expect(page.getByRole('heading', { name: /林知夏/ })).toBeVisible()
  await expect(page.getByRole('button', { name: '叫号并开始接诊' })).toBeVisible()
  await page.getByRole('navigation', { name: '医生端导航' }).getByRole('button', { name: '首页', exact: true }).click()
  await page.getByRole('textbox', { name: '搜索候诊患者' }).fill('不存在')
  await expect(page.getByText('未找到匹配的患者')).toBeVisible()
  await page.getByRole('button', { name: '清空搜索' }).click()
  await expect(page.getByRole('button', { name: '查看陈亦安详情' })).toBeVisible()
  await page.getByRole('button', { name: /陈予安医生邀请你替诊/ }).click()
  await expect(page).toHaveURL(/applications/)
  await expect(page.getByRole('main')).not.toContainText('林牧医生的停诊申请')
  await expect(page.getByRole('button', { name: '接受替诊' })).toBeVisible()
})

test('演示场景同步跨标签、刷新保留，科主任只增加科室待办，重置需确认', async ({ page, context }) => {
  await page.goto('/prototype/doctor-home')
  const other = await context.newPage()
  await other.goto('/prototype/doctor-home')
  await page.getByRole('button', { name: '演示设置' }).click()
  const controls = page.getByRole('dialog', { name: '原型演示设置' })
  await controls.getByLabel('演示场景').selectOption('ongoing')
  await controls.getByLabel('演示身份').selectOption('head')
  expect(await page.evaluate(() => Object.keys(JSON.parse(localStorage.getItem('medical-doctor-home-demo-v1')!)).sort())).toEqual(['role', 'scenario'])
  await controls.getByRole('button', { name: '完成设置' }).click()
  await expect(other.getByRole('button', { name: '继续接诊', exact: true }).first()).toBeVisible()
  await expect(other.getByRole('button', { name: /林牧医生的停诊申请/ })).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: '继续接诊', exact: true }).first().click()
  await expect(page.getByRole('heading', { name: /林知夏/ })).toBeVisible()
  await page.getByRole('button', { name: '标记过号', exact: true }).click()
  await page.getByRole('dialog', { name: '确认标记过号' }).getByRole('button', { name: '确认过号' }).click()
  await page.getByRole('button', { name: '演示设置' }).click()
  await controls.getByLabel('演示场景').selectOption('upcoming')
  await controls.getByRole('button', { name: '完成设置' }).click()
  await page.getByRole('navigation', { name: '医生端导航' }).getByRole('button', { name: '首页', exact: true }).click()
  await expect(page.getByRole('heading', { name: '下一场问诊，准备就绪。' })).toBeVisible()
  await expect(page.getByText('下一场尚未开放签到')).toBeVisible()
  await page.getByRole('button', { name: '演示设置' }).click()
  await controls.getByLabel('演示场景').selectOption('finished')
  await controls.getByRole('button', { name: '完成设置' }).click()
  await expect(page.getByRole('heading', { name: '今天的诊疗，辛苦了。' })).toBeVisible()
  await expect(page.getByRole('main').getByRole('button', { name: '进入接诊工作台', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '演示设置' }).click()
  await controls.getByRole('button', { name: '重置演示', exact: true }).click()
  await controls.getByRole('button', { name: '取消', exact: true }).click()
  await expect(controls.getByLabel('演示场景')).toHaveValue('finished')
  await controls.getByRole('button', { name: '重置演示', exact: true }).click()
  await controls.getByRole('button', { name: '确认重置', exact: true }).click()
  await expect(page.getByRole('heading', { name: '今日诊疗，从容有序。' })).toBeVisible()
  await expect(other.getByRole('heading', { name: '今日诊疗，从容有序。' })).toBeVisible()
  await expect(page.getByRole('button', { name: /林牧医生的停诊申请/ })).toHaveCount(0)
})

