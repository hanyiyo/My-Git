test('损坏的本地演示设置可恢复且入口在刷新后仍可访问', async ({ page }) => {
  await page.goto('/prototype/doctor-home')
  await page.evaluate(() => localStorage.setItem('medical-doctor-home-demo-v1', '{bad-data'))
  await page.reload()
  await expect(page.getByRole('heading', { name: '今日诊疗，从容有序。' })).toBeVisible()
  await page.getByRole('button', { name: '演示设置' }).click()
  await expect(page.getByRole('alert')).toContainText('已恢复默认场景')
  await page.getByRole('dialog').getByRole('button', { name: '完成设置' }).click()
  await page.getByRole('navigation', { name: '医生端导航' }).getByRole('button', { name: '申请处理', exact: true }).click()
  await page.reload()
  await expect(page.getByRole('heading', { name: '申请处理', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '关闭申请处理标签' })).toBeVisible()
})
